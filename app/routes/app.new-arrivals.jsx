const dateString = (date) =>
  `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
const monthString = (date) => dateString(date).slice(0, 7);
function monthLabel(month) {
  const date = new Date(`${month}${month.length === 7 ? "-01" : ""}T00:00:00`);
  if (month.length === 10) {
    const end = new Date(date);
    end.setDate(end.getDate() + 6);
    const startLabel = date.toLocaleDateString("en-US", {
      month: "short",
      day: "numeric",
    });
    const endLabel = end.toLocaleDateString("en-US", {
      month: "short",
      day: "numeric",
      year: "2-digit",
    });
    return `${startLabel}–${endLabel}`;
  }
  return date
    .toLocaleDateString("en-US", { month: "short", year: "2-digit" })
    .replace(" ", "-");
}
function startOfWeek(value) {
  const date = new Date(`${value}T00:00:00`);
  const day = date.getDay();
  date.setDate(date.getDate() - (day === 0 ? 6 : day - 1));
  return dateString(date);
}
function weeksBetween(start, end) {
  const result = [];
  const cursor = new Date(`${startOfWeek(start)}T00:00:00`);
  const final = startOfWeek(end);
  while (dateString(cursor) <= final) {
    result.push(dateString(cursor));
    cursor.setDate(cursor.getDate() + 7);
  }
  return result;
}
function shiftMonth(month, offset) {
  const [year, value] = month.split("-").map(Number);
  return monthString(new Date(year, value - 1 + offset, 1));
}
function monthsBetween(start, end) {
  const result = [];
  for (let value = start; value <= end; value = shiftMonth(value, 1))
    result.push(value);
  return result;
}
function monthBounds(month, yesterday) {
  const [year, value] = month.split("-").map(Number);
  const naturalEnd = dateString(new Date(year, value, 0));
  return {
    start: `${month}-01`,
    end: naturalEnd > yesterday ? yesterday : naturalEnd,
  };
}
function weekBounds(week, yesterday) {
  const start = new Date(`${week}T00:00:00`);
  const endDate = new Date(start);
  endDate.setDate(endDate.getDate() + 6);
  const naturalEnd = dateString(endDate);
  return { start: week, end: naturalEnd > yesterday ? yesterday : naturalEnd };
}
const numericId = (value) => String(value ?? "").replace(/\D/g, "");
function numberFrom(row, key) {
  return Number(row?.[key]) || 0;
}

function normalizeRange(url, now = new Date()) {
  const yesterdayDate = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() - 1,
  );
  const yesterday = dateString(yesterdayDate);
  const currentMonth = monthString(yesterdayDate);
  const earliestMonth = shiftMonth(currentMonth, -17);
  const earliest = `${earliestMonth}-01`;
  const defaultStart = `${shiftMonth(currentMonth, -14)}-01`;
  const valid = (value) => /^\d{4}-\d{2}-\d{2}$/.test(value || "");
  let start = valid(url.searchParams.get("start"))
    ? url.searchParams.get("start")
    : defaultStart;
  let end = valid(url.searchParams.get("end"))
    ? url.searchParams.get("end")
    : yesterday;
  start = start < earliest ? earliest : start > yesterday ? yesterday : start;
  end = end > yesterday ? yesterday : end < earliest ? earliest : end;
  if (start > end) [start, end] = [end, start];
  const classification =
    url.searchParams.get("classification") === "tag" ? "tag" : "type";
  const interval =
    url.searchParams.get("interval") === "week" ? "week" : "month";
  return {
    start,
    end,
    startMonth: start.slice(0, 7),
    endMonth: end.slice(0, 7),
    earliest,
    earliestMonth,
    currentMonth,
    yesterday,
    classification,
    interval,
  };
}

async function mapConcurrent(items, limit, worker) {
  const output = new Array(items.length);
  let next = 0;
  async function consume() {
    while (next < items.length) {
      const index = next++;
      output[index] = await worker(items[index]);
    }
  }
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, consume),
  );
  return output;
}

async function fetchProductsByIds(admin, productIds) {
  const batches = [];
  for (let index = 0; index < productIds.length; index += 250)
    batches.push(productIds.slice(index, index + 250));
  const results = await mapConcurrent(batches, 2, async (batch) => {
    const response = await admin.graphql(
      `#graphql
      query NewArrivalMissingProducts($ids: [ID!]!) {
        nodes(ids: $ids) {
          ... on Product { id title productType tags handle featuredImage { url altText } }
        }
      }`,
      { variables: { ids: batch.map((id) => `gid://shopify/Product/${id}`) } },
    );
    const json = await response.json();
    return (json.data?.nodes || []).filter(Boolean);
  });
  return results.flat();
}

async function fetchPeriod(
  admin,
  shop,
  period,
  interval,
  yesterday,
  selectedStart,
  selectedEnd,
) {
  const bounds =
    interval === "week"
      ? weekBounds(period, yesterday)
      : monthBounds(period, yesterday);
  const start = bounds.start < selectedStart ? selectedStart : bounds.start;
  const end = bounds.end > selectedEnd ? selectedEnd : bounds.end;
  const cached = (dataset, query) =>
    runWithAnalyticsCache({
      shop,
      dataset: `new-arrival-${interval}-${dataset}-${period}`,
      rangeStart: start,
      rangeEnd: end,
      run: () => runShopifyQL(admin, query),
    });
  const [inventory, sales, storeSales, landingSessions] = await Promise.all([
    cached(
      "inventory-v2",
      `FROM inventory SHOW starting_inventory_units, ending_inventory_units GROUP BY product_id, product_title SINCE ${start} UNTIL ${end}`,
    ),
    cached(
      "product-sales-v2",
      `FROM sales SHOW total_sales, orders GROUP BY product_id, product_title SINCE ${start} UNTIL ${end}`,
    ),
    cached(
      "store-sales",
      `FROM sales SHOW total_sales SINCE ${start} UNTIL ${end}`,
    ),
    cached(
      "landing-sessions",
      `FROM sessions SHOW sessions WHERE landing_page_type = 'product' GROUP BY landing_page_path SINCE ${start} UNTIL ${end}`,
    ),
  ]);
  return { period, inventory, sales, storeSales, landingSessions };
}

export const loader = async ({ request }) => {
  const { admin, session } = await authenticate.admin(request);
  const range = normalizeRange(new URL(request.url));
  const months =
    range.interval === "week"
      ? weeksBetween(range.start, range.end)
      : monthsBetween(range.startMonth, range.endMonth);
  const shopPromise = admin
    .graphql(
      `#graphql
    query NewArrivalShop {
      shop {
        currencyCode
        myshopifyDomain
        primaryDomain { url }
      }
    }`,
    )
    .then((response) => response.json())
    .then((json) => ({
      currency: json.data?.shop?.currencyCode || "USD",
      shopUrl: json.data?.shop?.primaryDomain?.url || "",
      storeHandle: String(json.data?.shop?.myshopifyDomain || "").replace(
        /\.myshopify\.com$/i,
        "",
      ),
    }));
  const [catalog, shopInfo, monthly] = await Promise.all([
    getProductCatalog(admin, session.shop),
    shopPromise,
    mapConcurrent(months, 2, (period) =>
      fetchPeriod(
        admin,
        session.shop,
        period,
        range.interval,
        range.yesterday,
        range.start,
        range.end,
      ),
    ),
  ]);
  const catalogById = new Map(
    catalog.products.map((product) => [numericId(product.id), product]),
  );
  const analyticsProductIds = new Set(
    monthly
      .flatMap((result) => [
        ...result.inventory.rows.map((row) => numericId(row.product_id)),
        ...result.sales.rows.map((row) => numericId(row.product_id)),
      ])
      .filter(Boolean),
  );
  const missingIds = [...analyticsProductIds].filter(
    (id) =>
      !catalogById.has(id) ||
      catalogById.get(id).featuredImage === undefined ||
      (range.classification === "tag" &&
        catalogById.get(id).tags === undefined),
  );
  if (missingIds.length) {
    const enrichedProducts = await fetchProductsByIds(admin, missingIds);
    for (const product of enrichedProducts)
      catalogById.set(numericId(product.id), product);
  }
  const productIdByHandle = new Map(
    [...catalogById]
      .map(([id, product]) => [product.handle, id])
      .filter(([handle]) => handle),
  );
  const sourceRows = [];
  const monthlyStoreSales = {};
  const warnings = [];
  const debug = [];
  for (const result of monthly) {
    const inventoryById = new Map(
      result.inventory.rows.map((row) => [numericId(row.product_id), row]),
    );
    const salesById = new Map(
      result.sales.rows.map((row) => [numericId(row.product_id), row]),
    );
    const sessionsById = new Map();
    for (const row of result.landingSessions.rows) {
      const match = String(row.landing_page_path || "").match(
        /\/products\/([^/?#]+)/,
      );
      if (!match) continue;
      let handle = match[1];
      try {
        handle = decodeURIComponent(handle);
      } catch {
        /* Keep Shopify's original handle if malformed. */
      }
      const productId = productIdByHandle.get(handle);
      if (productId)
        sessionsById.set(
          productId,
          (sessionsById.get(productId) || 0) + numberFrom(row, "sessions"),
        );
    }
    for (const productId of new Set([
      ...inventoryById.keys(),
      ...salesById.keys(),
      ...sessionsById.keys(),
    ])) {
      if (!productId) continue;
      const product = catalogById.get(productId) || {};
      const inventory = inventoryById.get(productId) || {};
      const sales = salesById.get(productId) || {};
      const storefrontUrl =
        product.handle && shopInfo.shopUrl
          ? `${shopInfo.shopUrl.replace(/\/$/, "")}/products/${product.handle}`
          : "";
      const adminUrl = shopInfo.storeHandle
        ? `https://admin.shopify.com/store/${shopInfo.storeHandle}/products/${productId}`
        : "";
      sourceRows.push({
        productId,
        period: result.period,
        title:
          product.title ||
          sales.product_title ||
          inventory.product_title ||
          `Product ${productId}`,
        productType: product.productType || "Others",
        productTags: product.tags || [],
        productUrl: storefrontUrl || adminUrl,
        handle: product.handle || "",
        imageUrl: product.featuredImage?.url || "",
        startingInventory: numberFrom(inventory, "starting_inventory_units"),
        endingInventory: numberFrom(inventory, "ending_inventory_units"),
        totalSales: numberFrom(sales, "total_sales"),
        orders: numberFrom(sales, "orders"),
        landingSessions: sessionsById.get(productId) || 0,
      });
    }
    monthlyStoreSales[result.period] = result.storeSales.rows.reduce(
      (sum, row) => sum + numberFrom(row, "total_sales"),
      0,
    );
    for (const [label, query] of [
      ["Inventory", result.inventory],
      ["Product sales", result.sales],
      ["Store sales", result.storeSales],
      ["Landing sessions", result.landingSessions],
    ]) {
      if (query.error)
        warnings.push(`${result.period} ${label}: ${query.error}`);
      if (query.truncated)
        warnings.push(
          `${result.period} ${label}: reached the 100,000-row limit.`,
        );
      debug.push({
        month: result.period,
        label,
        rows: query.rows.length,
        cache: query.cacheStatus || "live",
        attempts: query.attempts || 1,
        time: query.elapsedMs || 0,
      });
    }
  }
  return {
    report: generateNewArrivalReport(
      sourceRows,
      months,
      monthlyStoreSales,
      range.classification,
    ),
    currency: shopInfo.currency,
    range,
    warnings: [...new Set(warnings)],
    debug,
    catalogSource: catalog.source,
    catalogRefreshedAt: catalog.refreshedAt,
  };
};

function display(value, type, currency) {
  if (type === "percent") return `${((value || 0) * 100).toFixed(1)}%`;
  if (type === "currency")
    return new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency,
      maximumFractionDigits: 0,
    }).format(value || 0);
  return new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 }).format(
    value || 0,
  );
}

function heatClass(key, value) {
  if (
    ![
      "naSalesRate",
      "naInventoryRate",
      "typeSalesRate",
      "totalSalesRate",
      "conversionRate",
    ].includes(key)
  )
    return "";
  if (value > 0.3) return "heat-high";
  if (value < 0.05) return "heat-low";
  return "heat-mid";
}

function MetricValue({ type, value, currency }) {
  if (type === "inventory" && Number(value) === 0)
    return <span className="oos-pill">0 · OOS</span>;
  return display(value, type, currency);
}

