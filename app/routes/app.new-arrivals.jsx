function MetricTooltip({ name, definition, formula, tone = "inventory" }) {
  const [position, setPosition] = useState(null);
  const show = (event) => {
    const rect = event.currentTarget.getBoundingClientRect();
    const width = 290;
    setPosition({
      top: Math.min(rect.bottom + 8, window.innerHeight - 170),
      left: Math.max(
        12,
        Math.min(rect.left - 8, window.innerWidth - width - 12),
      ),
    });
  };
  return (
    <>
      <span
        className="metric-info-trigger"
        role="button"
        tabIndex="0"
        aria-label={`Explain ${name}`}
        onMouseEnter={show}
        onMouseLeave={() => setPosition(null)}
        onFocus={show}
        onBlur={() => setPosition(null)}
        onClick={(event) => event.stopPropagation()}
        onKeyDown={(event) => {
          if (event.key === "Enter" || event.key === " ") {
            event.preventDefault();
            event.stopPropagation();
            show(event);
          }
        }}
      >
        ⓘ
      </span>
      {position &&
        typeof document !== "undefined" &&
        createPortal(
          <div
            className="metric-tooltip"
            style={{ top: position.top, left: position.left }}
            role="tooltip"
          >
            <div className={`logic-badge ${tone}`}>{name}</div>
            <p>{definition}</p>
            <code>Formula: {formula}</code>
          </div>,
          document.body,
        )}
    </>
  );
}

